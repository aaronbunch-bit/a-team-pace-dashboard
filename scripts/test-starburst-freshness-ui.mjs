import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
import {validateReviewedLedgerRules} from '../functions/_shared/starburst-reviewed-ledgers.mts';
const html=fs.readFileSync(new URL('../index.html',import.meta.url),'utf8');
const start=html.indexOf("  const statusEl = document.getElementById('liveActualsStatus');");
const end=html.indexOf('  syncLandingLiveStatus();',start);
assert(start>0&&end>start);
const el={textContent:'',style:{}};
const data={sourceStale:true,provisional:true,sourceUpdatedAt:'2026-10-02 22:00:13.078424 UTC',fetchedAt:'2026-10-05T13:00:00Z',sourceStaleReason:'Totals may be incomplete.'};
vm.runInNewContext(html.slice(start,end),{data,document:{getElementById:()=>el},Date,Number});
assert.match(el.textContent,/Sync delayed/);
assert.match(el.textContent,/Last checked Oct 5, 8:00 AM CT/);
assert(!el.textContent.includes('feed OK'));
assert.equal(el.style.color,'#dc2626');
Object.assign(data,{combined:{addedPurchases:2},exportStale:true,sourceStale:false,sourceStaleReason:undefined,unresolvedCount:1});
vm.runInNewContext(html.slice(start,end),{data,document:{getElementById:()=>el},Date,Number});
assert.match(el.textContent,/Sync working/);
assert.equal(el.style.color,'#16a34a');
assert.match(el.title,/2 purchases reconstructed/);
assert.match(el.title,/1 records awaiting review/);
assert.match(el.title,/export is delayed/);
assert(!el.textContent.includes('reconstructed'));
assert(!el.textContent.includes('feed OK'));
for(const rules of [null,{}, {schemaVersion:1,reviewedLedgers:{},excludedLedgerIds:[{}],reviewedAt:'2020-01-01'}])assert.throws(()=>validateReviewedLedgerRules(rules));
assert.doesNotThrow(()=>validateReviewedLedgerRules({schemaVersion:1,reviewedLedgers:{},excludedLedgerIds:[],reviewedAt:'2020-01-01'}));
console.log('Freshness UI shows source age separately from query time in Central; invalid private rules fail closed.');
